    public static IReadOnlyList<(string Code, string Name)> All { get; } = Table
        .OrderBy(entry => SortKey(entry.Name), StringComparer.Ordinal)
        .ThenBy(entry => entry.Name, StringComparer.Ordinal)
        .ToList();

    private static string SortKey(string name)
    {
        var buffer = new char[name.Length];
        for (var index = 0; index < name.Length; index++)
        {
            buffer[index] = char.ToLowerInvariant(StripAccent(name[index]));
        }

        return new string(buffer);
    }

    private static char StripAccent(char letter) => letter switch
    {
        'á' or 'à' or 'â' or 'ã' or 'ä' or 'Á' or 'À' or 'Â' or 'Ã' or 'Ä' => 'a',
        'é' or 'è' or 'ê' or 'ë' or 'É' or 'È' or 'Ê' or 'Ë' => 'e',
        'í' or 'ì' or 'î' or 'ï' or 'Í' or 'Ì' or 'Î' or 'Ï' => 'i',
        'ó' or 'ò' or 'ô' or 'õ' or 'ö' or 'Ó' or 'Ò' or 'Ô' or 'Õ' or 'Ö' => 'o',
        'ú' or 'ù' or 'û' or 'ü' or 'Ú' or 'Ù' or 'Û' or 'Ü' => 'u',
        'ç' or 'Ç' => 'c',
        _ => letter,
    };
